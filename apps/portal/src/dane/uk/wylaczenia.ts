export interface PozycjaZeZrodlem extends PozycjaUk {
  /** Paragrafy OWU — z polskiego pliku, w zapisie polskim („§ 11 ust. 1 lit. g"). */
  zrodla: string;
  /** Polski artykuł, który omawia pozycję szerzej. */
  wiecej?: Grupa['pozycje'][number]['wiecej'];
}

/**
 * Przekład spięty z polskim źródłem: te same grupy i pozycje, a przy każdej
 * paragrafy i odnośnik z polskiego pliku. Rozjazd liczby grup albo pozycji
 * przerywa build — lepiej nie wdrożyć strony, niż wdrożyć listę wyłączeń,
 * w której przekład stoi przy cudzym paragrafie.
 */
export function polaczone(): { tytul: string; pozycje: PozycjaZeZrodlem[] }[] {
  if (GRUPY_UK.length !== GRUPY.length) {
    throw new Error(`Wyłączenia: ${GRUPY.length} grup po polsku, ${GRUPY_UK.length} po ukraińsku.`);
  }
  return GRUPY_UK.map((g, i) => {
    const pl = GRUPY[i];
    if (g.pozycje.length !== pl.pozycje.length) {
      throw new Error(`Wyłączenia, grupa „${pl.tytul}": ${pl.pozycje.length} pozycji po polsku, `
        + `${g.pozycje.length} po ukraińsku.`);
    }
    return {
      tytul: g.tytul,
      pozycje: g.pozycje.map((p, j) => ({ ...p, zrodla: pl.pozycje[j].zrodla, wiecej: pl.pozycje[j].wiecej })),
    };
  });
}
